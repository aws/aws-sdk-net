            var fromAbsent = context.FromDocument<NullHandlingWithDefault>(
                new Document { ["Id"] = new Primitive("n1") });

            Assert.AreEqual(42, fromNull.Count);
            Assert.AreEqual(42, fromAbsent.Count, "A stored NULL and a missing attribute must agree.");
        }

