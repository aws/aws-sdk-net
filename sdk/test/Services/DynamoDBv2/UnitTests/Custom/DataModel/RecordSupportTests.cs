        [TestMethod]
        public void VersionViaTypeMapping_AsConstructorArgument_Throws()
        {
            // Type-mapping configuration is applied after PopulateConfigFromType, so constructor-argument
            // resolution must run after mappings to observe the mapping-level version flag and reject it.
            var mapping = new Amazon.Util.TypeMapping(typeof(MappingVersionedRecord), "MappingVersionedRecord");
            mapping.AddProperty(new Amazon.Util.PropertyConfig("Version") { Version = true });
            Amazon.AWSConfigsDynamoDB.Context.AddMapping(mapping);

            try
            {
                var context = CreateContext();
                var flatConfig = new DynamoDBFlatConfig(new DynamoDBOperationConfig(), context.Config);

                var ex = Assert.ThrowsExactly<InvalidOperationException>(() =>
                    context.StorageConfigCache.GetConfig<MappingVersionedRecord>(flatConfig));

                StringAssert.Contains(ex.Message, "version");
                StringAssert.Contains(ex.Message, "cannot be supplied through a constructor parameter");
            }
            finally
            {
                Amazon.AWSConfigsDynamoDB.Context.TypeMappings.Remove(typeof(MappingVersionedRecord));
            }
        }

