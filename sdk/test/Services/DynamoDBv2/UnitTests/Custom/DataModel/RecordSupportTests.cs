    [TestClass]
    public class RecordSupportTests
    {
        // Positional record: generated properties are get/init, populated through the primary constructor.
        public record PositionalRecord(
            [property: DynamoDBHashKey] string Id,
            string Name,
            int Age,
            int? Score = 42);

        // Record with an explicit init-only property.
        public record InitRecord
        {
            [DynamoDBHashKey]
            public string Id { get; init; }
            public string Name { get; init; }
        }

        // Value-type positional record.
        public readonly record struct RecordStruct(
            [property: DynamoDBHashKey] string Id,
            int Count);

        // Non-positional record struct: only the synthesized parameterless constructor, populated via
        // zero-initialization + member assignment.
        public record struct NonPositionalRecordStruct
        {
            [DynamoDBHashKey]
            public string Id { get; set; }
            public int Count { get; set; }
        }

        // Class whose single public constructor takes the declaring type. This must NOT be treated as a
        // (compiler-generated, non-public) copy constructor and dropped during binding-constructor selection.
        public class SelfParamCtorType
        {
            public SelfParamCtorType(SelfParamCtorType other) { Other = other; }

            public SelfParamCtorType Other { get; }
        }

        // Immutable POCO with get-only properties supplied through a single parameterized constructor.
        public class ImmutablePoco
        {
            public ImmutablePoco(string id, string name)
            {
                Id = id;
                Name = name;
            }

            [DynamoDBHashKey]
            public string Id { get; }
            public string Name { get; }
        }

        // Ambiguous: two eligible parameterized constructors and no [DynamoDBConstructor] marker.
        public class AmbiguousCtors
        {
            public AmbiguousCtors(string id) { Id = id; }
            public AmbiguousCtors(string id, string name) { Id = id; Name = name; }

            [DynamoDBHashKey]
            public string Id { get; }
            public string Name { get; }
        }

        // Abstract type with a public parameterized constructor. It cannot be instantiated, so it must be
        // rejected with the normal unsupported-type error rather than selecting a binding constructor and
        // failing later inside ConstructorInfo.Invoke.
        public abstract class AbstractWithPublicCtor
        {
            public AbstractWithPublicCtor(string id) { Id = id; }

            [DynamoDBHashKey]
            public string Id { get; }
        }

        // Version / atomic counter / auto-generated timestamp as constructor parameters are not supported:
        // the SDK must write the server-generated value back after a save/update, which is impossible for an
        // immutable member.
        public record VersionedRecord(
            [property: DynamoDBHashKey] string Id,
            [property: DynamoDBVersion] int? Version);

        public record CounterRecord(
            [property: DynamoDBHashKey] string Id,
            [property: DynamoDBAtomicCounter] long? Count);

        public record TimestampRecord(
            [property: DynamoDBHashKey] string Id,
            [property: DynamoDBAutoGeneratedTimestamp] DateTime? UpdatedAt);

        public record IfNotExistsRecord(
            [property: DynamoDBHashKey] string Id,
            [property: DynamoDbUpdateBehavior(UpdateBehavior.IfNotExists)] string Name);

        // Flattened constructor argument whose descendant holds a server-managed (version) value. Because the
        // flattened parent is skipped by PopulateInstance, the descendant would be left stale after a save/update,
        // so the combination must be rejected by recursing into the flattened member's children.
        public record FlattenedWithVersionRecord(
            [property: DynamoDBHashKey] string Id,
            [property: DynamoDBFlatten] VersionedChild Meta);

        public class VersionedChild
        {
            public string ChildName { get; set; }

            [DynamoDBVersion]
            public int? Version { get; set; }
        }

        // Plain positional record whose "Version" parameter is marked as a version via a type mapping
        // (not an attribute). Used to verify constructor-argument resolution runs after mappings are applied.
        public record MappingVersionedRecord(
            [property: DynamoDBHashKey] string Id,
            int? Version);

        // Disambiguated with [DynamoDBConstructor].
        public class MarkedCtor
        {
            public MarkedCtor(string id) { Id = id; }

            [DynamoDBConstructor]
            public MarkedCtor(string id, string name) { Id = id; Name = name; }

            [DynamoDBHashKey]
            public string Id { get; }
            public string Name { get; }
        }

        // Mutable type with a parameterless constructor is unaffected by the binding-constructor path.
        public class MutablePoco
        {
            [DynamoDBHashKey]
            public string Id { get; set; }
            public string Name { get; set; }
        }

        // Positional record with a flattened member supplied through the constructor.
        public record FlattenedRecord(
            [property: DynamoDBHashKey] string Id,
            [property: DynamoDBFlatten] FlattenedChild Child);

        // The flattened member type is a mutable class (its children are stored at the top level).
        public class FlattenedChild
        {
            public string ChildName { get; set; }
            public int ChildValue { get; set; }
        }

        // Optional flattened constructor parameter defaulting to null (schema-evolution scenario).
        public record OptionalFlattenedRecord(
            [property: DynamoDBHashKey] string Id,
            [property: DynamoDBFlatten] FlattenedChild Child = null);

        // Mutable value-type (record struct) flattened child: has no binding constructor, so it is populated via
        // zero-initialization + member assignment (must not go through the reference-type-only instantiation path).
        public record struct FlattenValueChild
        {
            public string ChildName { get; set; }
            public int ChildValue { get; set; }
        }

        public class FlattenValueChildEntity
        {
            [DynamoDBHashKey]
            public string Id { get; set; }

            [DynamoDBFlatten]
            public FlattenValueChild Child { get; set; }
        }

        // Constructor-bound flattened member whose type itself contains a nested [DynamoDBFlatten] member.
        // The nested member's leaves are stored at the top level, so it must be materialized recursively.
        public record NestedFlattenRecord(
            [property: DynamoDBHashKey] string Id,
            [property: DynamoDBFlatten] OuterFlatten Outer);

        public class OuterFlatten
        {
            public string OuterName { get; set; }

            [DynamoDBFlatten]
            public InnerFlatten Inner { get; set; }
        }

        public class InnerFlatten
        {
            public string InnerName { get; set; }
            public int InnerValue { get; set; }
        }

        // Flattening an immutable (constructor-populated) child type is not supported: it would serialize but
        // fail to load, since flattened values are reconstructed with a parameterless constructor.
        public record ImmutableFlattenChild(string ChildName, int ChildValue);

        public class FlattenImmutableChildEntity
        {
            [DynamoDBHashKey]
            public string Id { get; set; }

            [DynamoDBFlatten]
            public ImmutableFlattenChild Child { get; set; }
        }

        // record struct that also declares an explicit public parameterless constructor. The primary
        // constructor must still be selected for binding because value types cannot use the
        // parameterless instantiation path.
        public readonly record struct StructWithParameterless(
            [property: DynamoDBHashKey] string Id,
            int Count)
        {
            public StructWithParameterless() : this(string.Empty, 0) { }
        }

        // Type with a parameterless constructor where [DynamoDBConstructor] forces constructor binding.
        public class ForcedBindingType
        {
            public ForcedBindingType() { }

            [DynamoDBConstructor]
            public ForcedBindingType(string id, string name)
            {
                Id = id;
                Name = name;
            }

            [DynamoDBHashKey]
            public string Id { get; set; }
            public string Name { get; set; }
        }

