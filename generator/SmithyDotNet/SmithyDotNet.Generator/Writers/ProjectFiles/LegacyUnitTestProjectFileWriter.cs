using SmithyDotNet.Generator.Generation.Manifests;
using SmithyDotNet.Generator.Generation.ProjectFiles;

namespace SmithyDotNet.Generator.Writers.ProjectFiles;

/// <summary>
/// Emits <c>sdk/test/UnitTests/AWSSDK.UnitTests.{NetFramework|NetStandard}.csproj</c>, which compile every service's
/// unit tests against that variant, as C2J's <c>UnitTestProjectFileCreator</c> does through its
/// <c>VS2017ProjectFile.tt</c>. The output matches C2J's (trimmed, tabs as four spaces) apart from line endings, so the
/// committed files don't change.
/// </summary>
public sealed class LegacyUnitTestProjectFileWriter(UnitTestProjectManifest manifest)
{
    public string Write(ServiceProjectConfiguration configuration)
    {
        var variant = configuration.Variant;
        var isNetFramework = variant == ServiceProjectConfigurations.NetFramework.Variant;
        var assemblyName = $"AWSSDK.UnitTests.{variant}";
        // The NetStandard variant runs only on the MSTest .NET targets: a test project can't run on netstandard2.0.
        var targetFrameworks = isNetFramework ? "$(SdkNetFrameworkTargets)" : "$(SdkMSTestNetTestTargets)";
        var writer = new CodeWriter();
        writer.WriteXmlBlock("""<Project Sdk="Microsoft.NET.Sdk">""", "Project", () =>
        {
            writer.WriteLine("<!-- This project file is generated. Do not edit this file directly. -->");
            writer.WriteLine("<PropertyGroup>");
            // C2J's template indents this one line by three spaces.
            writer.WriteLine(""" <RunAnalyzersDuringBuild Condition="'$(RunAnalyzersDuringBuild)'==''">true</RunAnalyzersDuringBuild>""");
            writer.Indent(() =>
            {
                writer.WriteLine($"<TargetFrameworks>{targetFrameworks}</TargetFrameworks>");
                writer.WriteLine($"<DefineConstants>$(DefineConstants);{string.Join(";", manifest.DefineConstants)}</DefineConstants>");
                writer.WriteLine("<!-- AWS_ASYNC_ENUMERABLES_API gates the async-enumerable/paginator APIs, which are unavailable on");
                writer.WriteLine("     .NET Framework. The identifier-based condition covers every non-.NETFramework target");
                writer.WriteLine("     (netstandard2.0, netcoreapp3.1, net8.0, and any future target) without hardcoding TFM names.");
                writer.WriteLine("     On .NET Framework the condition is false so the constant is not defined. -->");
                writer.WriteLine($"""<DefineConstants Condition="{ProjectFileSections.IsNotNetFramework}">$(DefineConstants);AWS_ASYNC_ENUMERABLES_API</DefineConstants>""");
                ProjectFileSections.WriteTestProjectProperties(writer, assemblyName, manifest.NoWarn);
            });
            writer.WriteLine("</PropertyGroup>");
            ProjectFileSections.WriteSigningChoose(writer, "../../awssdk.dll.snk");
            writer.WriteLine();
            WriteItemGroup(writer, ["""<Compile Include="../Services/*/UnitTests/**/*.cs"/>"""]);
            WriteItemGroup(writer, CompileRemoves(configuration.OtherVariantFolder, isNetFramework));
            writer.WriteLine();
            WriteItemGroup(writer,
            [
                $"""<ProjectReference Include="../../src/Core/AWSSDK.Core.{variant}.csproj"/>""",
                $"""<ProjectReference Include="../Common/{ProjectFileNames.CommonTest}"/>""",
                $"""<ProjectReference Include="../../../generator/ServiceClientGeneratorLib/{ProjectFileNames.GeneratorLib}"/>""",
                $"""<ProjectReference Include="../../../extensions/src/AWSSDK.Extensions.CrtIntegration/AWSSDK.Extensions.CrtIntegration.{variant}.csproj"/>""",
                $"""<ProjectReference Include="../../src/Services/*/*.{variant}.csproj"/>""",
                $"""<ProjectReference Include="../../test/Services/*/*.{variant}.csproj"/>""",
            ]);
            writer.WriteLine();
            WriteItemGroup(writer, manifest.PackageReferences.Select(package => $"""<PackageReference Include="{package.Id}" Version="{package.Version}"/>"""));
            writer.WriteLine();
            // C2J sorts each reference's targets before grouping references by them.
            static string Condition(FrameworkReference reference)
            {
                var targets = reference.Targets.Order(StringComparer.InvariantCulture).Select(target => $"'$(TargetFramework)' == '{target}'");
                return string.Join(" Or ", targets);
            }

            foreach (var group in manifest.FrameworkReferences.GroupBy(Condition))
            {
                WriteItemGroup(writer, group.Select(reference => $"""<Reference Include="{reference.Name}"/>"""), group.Key);
                writer.WriteLine();
            }
            WriteItemGroup(writer, manifest.EmbeddedResources.Select(resource => $"""<EmbeddedResource Include="{resource}"/>"""));
            writer.WriteLine();
        });
        return writer.ToRawString().TrimEnd();
    }

    // As C2J's template spells them: bin/obj also drop None items, and a path is used as is.
    private IEnumerable<string> CompileRemoves(string otherVariantFolder, bool isNetFramework)
    {
        var folders = manifest.ExcludeFolders.Append(otherVariantFolder);
        // MobileAnalytics ships only for .NET Framework, as in C2J.
        if (!isNetFramework)
        {
            folders = folders.Append("../Services/MobileAnalytics/UnitTests/**/*.cs");
        }

        foreach (var folder in folders)
        {
            if (folder is "bin" or "obj")
            {
                yield return $"""<Compile Remove="**/{folder}/**"/>""";
                yield return $"""<None Remove="**/{folder}/**" />""";
            }
            else
            {
                yield return folder.Contains('/') ? $"""<Compile Remove="{folder}"/>""" : $"""<Compile Remove="**/{folder}/**"/>""";
            }
        }
    }

    private static void WriteItemGroup(CodeWriter writer, IEnumerable<string> items, string condition = "")
    {
        writer.WriteXmlBlock(condition.Length == 0 ? "<ItemGroup>" : $"""<ItemGroup Condition="{condition}">""", "ItemGroup", () =>
        {
            foreach (var item in items)
            {
                writer.WriteLine(item);
            }
        });
    }
}
